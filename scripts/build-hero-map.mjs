// Builds the SVG path data for the animated home-page map (Iran → Mashhad).
//
// Inputs (downloaded once into a scratch dir, not committed):
//   - Iran provinces: geoBoundaries gbOpen IRN ADM1 (CC BY 4.0)
//     https://media.githubusercontent.com/media/wmgeolab/geoBoundaries/main/releaseData/gbOpen/IRN/ADM1/geoBoundaries-IRN-ADM1_simplified.geojson
//   - Mashhad main roads: OpenStreetMap via Overpass (ODbL), query:
//     [out:json];way["highway"~"^(motorway|trunk|primary|secondary)$"](36.20,59.40,36.42,59.72);out geom;
//
// Usage: node scripts/build-hero-map.mjs <provinces.geojson> <roads.json>
// Output: src/components/hero-map/iran-data.ts, src/components/hero-map/mashhad-data.ts
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const [provPath, roadsPath] = process.argv.slice(2);
if (!provPath || !roadsPath) {
  console.error("usage: node scripts/build-hero-map.mjs <provinces.geojson> <roads.json>");
  process.exit(1);
}

// Equirectangular projection shared by both layers so the camera can fly between them.
const K = 100;
const COS = Math.cos((32.5 * Math.PI) / 180);
const LON0 = 44;
const LAT0 = 39.8;
const px = (lon) => (lon - LON0) * K * COS;
const py = (lat) => (LAT0 - lat) * K;

function simplify(pts, tol) {
  if (pts.length < 3) return pts;
  const sq = tol * tol;
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [ax, ay] = pts[a];
    const [bx, by] = pts[b];
    const dx = bx - ax;
    const dy = by - ay;
    const len = dx * dx + dy * dy;
    let max = 0;
    let idx = -1;
    for (let i = a + 1; i < b; i++) {
      const [x, y] = pts[i];
      let t = len ? ((x - ax) * dx + (y - ay) * dy) / len : 0;
      t = Math.max(0, Math.min(1, t));
      const ex = ax + t * dx - x;
      const ey = ay + t * dy - y;
      const d = ex * ex + ey * ey;
      if (d > max) {
        max = d;
        idx = i;
      }
    }
    if (max > sq && idx > 0) {
      keep[idx] = 1;
      stack.push([a, idx], [idx, b]);
    }
  }
  return pts.filter((_, i) => keep[i]);
}

const fmt = (n, dp) => {
  const s = n.toFixed(dp).replace(/\.?0+$/, "");
  return s === "-0" ? "0" : s;
};
function toPath(rings, dp, close) {
  return rings
    .map((r) => "M" + r.map(([x, y]) => `${fmt(x, dp)} ${fmt(y, dp)}`).join("L") + (close ? "Z" : ""))
    .join("");
}

// ---- Provinces -------------------------------------------------------------
const FA = {
  "Razavi Khorasan": "خراسان رضوی",
};
const geo = JSON.parse(readFileSync(provPath, "utf8"));
const byName = new Map();
for (const f of geo.features) {
  const name = f.properties.shapeName;
  const polys = f.geometry.type === "MultiPolygon" ? f.geometry.coordinates : [f.geometry.coordinates];
  const rings = [];
  for (const poly of polys) {
    const outer = poly[0].map(([lon, lat]) => [px(lon), py(lat)]);
    const s = simplify(outer, 1.4);
    if (s.length >= 4) rings.push(s);
  }
  // Mazandaran comes as two features (mainland + Ashuradeh); merge by name.
  byName.set(name, [...(byName.get(name) ?? []), ...rings]);
}
let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
const provinces = [...byName].map(([name, rings]) => {
  let sx = 0, sy = 0, n = 0;
  for (const r of rings)
    for (const [x, y] of r) {
      sx += x; sy += y; n++;
      minX = Math.min(minX, x); minY = Math.min(minY, y);
      maxX = Math.max(maxX, x); maxY = Math.max(maxY, y);
    }
  return { name, fa: FA[name] ?? null, cx: +(sx / n).toFixed(1), cy: +(sy / n).toFixed(1), d: toPath(rings, 1, true) };
});
// Stable draw order: west → east so the lines "sweep" toward Mashhad.
provinces.sort((a, b) => a.cx - b.cx);

// ---- Mashhad roads -----------------------------------------------------------
const osm = JSON.parse(readFileSync(roadsPath, "utf8"));
const MAJOR = new Set(["motorway", "trunk", "primary"]);
const major = [];
const minor = [];
for (const el of osm.elements) {
  if (!el.geometry) continue;
  const pts = el.geometry.map(({ lat, lon }) => [px(lon), py(lat)]);
  const s = simplify(pts, 0.025);
  if (s.length < 2) continue;
  (MAJOR.has(el.tags.highway) ? major : minor).push(s);
}

const hood = (fa, lat, lon) => ({ fa, x: +px(lon).toFixed(2), y: +py(lat).toFixed(2) });
const city = (fa, en, lat, lon) => ({ fa, en, x: +px(lon).toFixed(1), y: +py(lat).toFixed(1) });

